// Command sitedata writes site/assets/days.js for the course website: every phase and day from
// SYLLABUS.md, plus each written day's folder and the opening of its brief. The site is plain
// static files, so the output is committed. Run it again whenever a day is added or renamed:
//
//	go run ./tools/sitedata          write it
//	go run ./tools/sitedata -check   fail if it's out of date (for CI)
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/sagebeme/100-Days-of-Go/tools/internal/course"
)

type Phase struct {
	N     int    `json:"n"`
	Name  string `json:"name"`
	Learn string `json:"learn"`
	Ends  string `json:"ends"`
	First int    `json:"first"`
	Last  int    `json:"last"`
}

type Day struct {
	Day      int    `json:"day"`
	Phase    int    `json:"phase"`
	Title    string `json:"title"`
	Topic    string `json:"topic"`
	Capstone bool   `json:"capstone"`
	Path     string `json:"path"`  // the day's folder from the repo root; "" while it's only planned
	Brief    string `json:"brief"` // the opening of "The brief", as plain text; "" while planned
	Kata     bool   `json:"kata"`
}

// done[i] is whether SYLLABUS.md marks day i+1 as Done.
var done []bool

var (
	phaseHead = regexp.MustCompile(`^## Phase (\d+): (.+)$`)
	row       = regexp.MustCompile(`^\| (\d+) \| (.+?) \| (.*?) \| (Done|Planned) \|$`)
	dayHead   = regexp.MustCompile(`(?m)^# Day (\d+): (.+)$`)
)

func main() {
	check := flag.Bool("check", false, "fail if site/assets/days.js is out of date")
	flag.Parse()

	root, err := course.Root()
	if err != nil {
		fail("%v", err)
	}
	phases, days, err := parseSyllabus(filepath.Join(root, "SYLLABUS.md"))
	if err != nil {
		fail("SYLLABUS.md: %v", err)
	}
	written, err := course.Days(root)
	if err != nil {
		fail("%v", err)
	}
	for _, w := range written {
		if w.N < 1 || w.N > len(days) {
			fail("%s isn't in SYLLABUS.md", w.Dir)
		}
		d := &days[w.N-1]
		readme, err := os.ReadFile(filepath.Join(root, w.Dir, "README.md"))
		if err != nil {
			fail("%s has no README.md", w.Dir)
		}
		m := dayHead.FindStringSubmatch(string(readme))
		if m == nil || m[1] != strconv.Itoa(w.N) {
			fail(`%s/README.md must start with "# Day %d: Title"`, w.Dir, w.N)
		}
		d.Path = w.Dir
		d.Brief = brief(string(readme))
		d.Kata = course.Exists(filepath.Join(root, w.Dir, "kata"))
	}

	// The Status column has to match the repo: Done means the day's folder exists.
	for i, d := range days {
		if done[i] && d.Path == "" {
			fail("SYLLABUS.md marks day %d as Done, but there's no folder for it", d.Day)
		}
		if !done[i] && d.Path != "" {
			fail("day %d is written (%s); mark it Done in SYLLABUS.md", d.Day, d.Path)
		}
	}

	var b bytes.Buffer
	b.WriteString("// Generated by tools/sitedata from SYLLABUS.md and the day folders. Don't edit by hand.\n")
	p, _ := json.MarshalIndent(phases, "", "  ")
	fmt.Fprintf(&b, "window.GO_PHASES = %s;\n\nwindow.GO_DAYS = [\n", p)
	for i, d := range days {
		j, _ := json.Marshal(d)
		sep := ","
		if i == len(days)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "  %s%s\n", j, sep)
	}
	b.WriteString("];\n")

	out := filepath.Join(root, "site", "assets", "days.js")
	if *check {
		current, _ := os.ReadFile(out)
		if !bytes.Equal(current, b.Bytes()) {
			fail("site/assets/days.js is out of date. Run: go run ./tools/sitedata")
		}
		fmt.Printf("site/assets/days.js is up to date (%d days, %d written).\n", len(days), len(written))
		return
	}
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("Wrote %d days (%d written) in %d phases to site/assets/days.js\n", len(days), len(written), len(phases))
}

func parseSyllabus(path string) ([]Phase, []Day, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	defer f.Close()
	var phases []Phase
	var days []Day
	done = nil
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if m := phaseHead.FindStringSubmatch(line); m != nil {
			n, _ := strconv.Atoi(m[1])
			phases = append(phases, Phase{N: n, Name: m[2]})
			continue
		}
		if len(phases) == 0 {
			continue
		}
		cur := &phases[len(phases)-1]
		switch {
		case strings.HasPrefix(line, "Learn: "):
			cur.Learn = strings.TrimPrefix(line, "Learn: ")
		case strings.HasPrefix(line, "Ends with: "):
			cur.Ends = strings.TrimPrefix(line, "Ends with: ")
		default:
			m := row.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			n, _ := strconv.Atoi(m[1])
			if n != len(days)+1 {
				return nil, nil, fmt.Errorf("expected day %d, found day %d", len(days)+1, n)
			}
			title, capstone := strings.CutPrefix(m[2], "Capstone: ")
			days = append(days, Day{Day: n, Phase: cur.N, Title: title, Topic: m[3], Capstone: capstone})
			done = append(done, m[4] == "Done")
			if cur.First == 0 {
				cur.First = n
			}
			cur.Last = n
		}
	}
	if err := sc.Err(); err != nil {
		return nil, nil, err
	}
	if len(days) != 100 {
		return nil, nil, fmt.Errorf("expected 100 days, found %d", len(days))
	}
	return phases, days, nil
}

var (
	codeSpan = regexp.MustCompile("`([^`]*)`")
	bold     = regexp.MustCompile(`\*\*([^*]*)\*\*`)
	italic   = regexp.MustCompile(`\*([^*]*)\*`)
	link     = regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`)
	space    = regexp.MustCompile(`\s+`)
)

// brief returns the first paragraph of "## The brief" as plain text, cut to about 220 characters.
func brief(readme string) string {
	_, section, ok := strings.Cut(readme, "## The brief")
	if !ok {
		return ""
	}
	var para string
	for _, p := range strings.Split(section, "\n\n") {
		p = strings.TrimSpace(p)
		if p != "" && !strings.HasPrefix(p, "```") && !strings.HasPrefix(p, "|") && !strings.HasPrefix(p, "#") {
			para = p
			break
		}
	}
	for _, re := range []*regexp.Regexp{codeSpan, bold, italic, link} {
		para = re.ReplaceAllString(para, "$1")
	}
	text := strings.TrimSpace(space.ReplaceAllString(para, " "))
	if r := []rune(text); len(r) > 220 {
		cut := string(r[:220])
		cut = cut[:strings.LastIndex(cut, " ")]
		text = strings.TrimRight(cut, ",;:") + "…"
	}
	return text
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
